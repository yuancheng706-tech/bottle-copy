# p4_if.py — if / elif / else：讓程式自己做判斷
# 這是一串「假的」總加速度（單位 g），模擬瓶子倒下的過程：
#   站著（約 1 g）→ 倒下途中（變小）→ 撞到地面（很大）→ 躺著（約 1 g）

readings = [1.0, 1.0, 0.9, 0.4, 0.3, 3.8, 2.1, 1.1, 1.0]

TH_IMPACT = 2.5    # 超過這個值算「撞擊」

for m in readings:
    if m > TH_IMPACT:
        print(m, "g → 撞擊！")
    elif m > 0.8:
        print(m, "g → 正常")
    else:
        print(m, "g → no signal")

